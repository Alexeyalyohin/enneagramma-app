// без канцелярита») и подлежат вычитке методологом.
//
// Что важно сохранить при вычитке:
//   • ровно 6 триад грузят социальную ось, ровно 6 — гармоническую;
//   • у каждой триады ровно три варианта — по одному на каждое значение оси;
//   • порядок вариантов внутри триад намеренно разный, чтобы не было
//     позиционного смещения («всегда первый = ассертивный»);
//   • у каждой спорной пары ровно два различающих вопроса.

