// формулировок, но полного банка (12 триад + 3 вопроса центра + вопросы для
// спорных пар) в нём нет. Это контент-гэп спецификации, а не архитектурная
// недоделка: структура, оси и веса — строго по Чертежу (БЛОК 5), формулировки
