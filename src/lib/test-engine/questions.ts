/** Все вопросы триад и центра по порядку предъявления. */
export const ORDERED_BASE_QUESTIONS: readonly TriadQuestion[] = [
  ...TRIAD_QUESTIONS,
  ...CENTER_QUESTIONS,
]

const QUESTION_BY_ID = new Map<string, TriadQuestion>(
  ORDERED_BASE_QUESTIONS.map((question) => [question.id, question] as const)
)

const TIEBREAK_BY_ID = new Map<string, TiebreakQuestion>(
  Object.values(TIEBREAK_ITEMS)
    .flat()
    .map((question) => [question.id, question] as const)
)

export function findBaseQuestion(id: string): TriadQuestion | undefined {
  return QUESTION_BY_ID.get(id)
}

export function findTiebreakQuestion(id: string): TiebreakQuestion | undefined {
  return TIEBREAK_BY_ID.get(id)
}

export function hasTiebreakPair(pair: string): pair is TiebreakPairKey {
  return Object.prototype.hasOwnProperty.call(TIEBREAK_ITEMS, pair)
}
