-- Экран результата теста умеет показывать раннер-апа как альтернативный
-- портрет (только для tiebreak/borderline сессий, см. /api/test/result).
-- Если человек в момент клика «Получить разбор в Telegram» смотрит именно
-- на раннер-апа, это и есть тип, который он считает более точным — колонка
-- запоминает этот выбор, чтобы /api/leads/link-telegram записал в лид
-- именно его, а не исходного алгоритмического победителя.

ALTER TABLE public.test_sessions
  ADD COLUMN viewer_selected_type SMALLINT CHECK (viewer_selected_type BETWEEN 1 AND 9);

COMMENT ON COLUMN public.test_sessions.viewer_selected_type IS
  'Тип, который пользователь явно выбрал на экране результата вместо алгоритмического победителя (переключатель на раннер-апа). NULL — пользователь остался на исходном типе (или выбор не был близким). Пишет /api/leads/telegram-start в момент клика по кнопке Telegram; переписывается на каждый клик — актуально только последнее нажатое значение. Читает /api/leads/link-telegram при записи type/wing в leads. test_sessions.result при этом НЕ меняется — канонический результат теста остаётся как посчитан.';
